export const ICON_NAMES = Object.keys(GRIDS) as IconName[];

export const PixelIcon: React.FC<{
  name: IconName;
  size: number;
  ink?: string;
  accent?: string;
  style?: React.CSSProperties;
}> = ({ name, size, ink, accent = C.accent, style }) => {
  const world = useWorld();
  const inkColor = ink ?? world.ink;
  const rows = GRIDS[name];
  const n = rows.length;
  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${n} ${n}`}
      shapeRendering="crispEdges"
      style={{ display: "block", ...style }}
    >
      {rows.flatMap((row, y) =>
        row.split("").map((ch, x) =>
          ch === "." ? null : (
            <rect
              key={`${x}-${y}`}
              x={x}
              y={y}
              width={1}
              height={1}
              fill={ch === "a" ? accent : inkColor}
            />
          ),
        ),
      )}
    </svg>
  );
};
